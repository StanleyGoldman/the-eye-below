// Writes the make fragment make/assets.mk from assets/manifest.json:
// one rule per raw file, per cutout, and per processed asset, grouped
// by workflow. Also writes one small file per manifest entry under
// make/entries/, changed only when that entry changes, so editing one
// entry rebuilds one asset.
//
//   node scripts/gen-rules.ts        (make runs it when the manifest changes)

import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import path from "node:path";
import { WORKFLOW_FILES } from "./lib/comfy-api.ts";
import type { WorkflowKey } from "./lib/comfy-api.ts";
import { PROMPTS_FILE, animationOf, assetDir, extension, rawDir, readFallbacks, readManifest, readPrompts, resolvePrompt } from "./lib/manifest.ts";

const OUT = "make/assets.mk";
const ENTRIES = "make/entries";

function writeIfChanged(file: string, text: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8") === text) return false;
  mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.part`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
  return true;
}

const manifest = readManifest();
const prompts = readPrompts();
const fallbacks = new Set(readFallbacks());
const groups: Record<string, string[]> = { base: [], styled: [], frames: [], cutouts: [], music: [], sfx: [], processed: [] };
const rules: string[] = [];
let changed = 0;
const wanted = new Set<string>();

/** The file post-processing reads for an image: its cutout, or the raw image when it is opaque or keyed as a whole. */
function sourceOf(entry: (typeof manifest.assets)[number]): string {
  const dir = rawDir(entry.type);
  return entry.transparent && entry.key !== "all" ? path.join(dir, `${entry.id}.cut.png`) : path.join(dir, `${entry.id}.png`);
}

for (const entry of manifest.assets) {
  // The entry file holds what generation depends on. The seed is left out: choosing a different
  // attempt records its seed in the manifest, and that must not look like a new request.
  const { seed: _seed, ...rest } = entry;
  void _seed;
  const stamp = path.join(ENTRIES, `${entry.id}.json`);
  wanted.add(`${entry.id}.json`);
  if (writeIfChanged(stamp, `${JSON.stringify({ ...rest, resolvedPrompt: resolvePrompt(prompts, entry) }, null, 1)}\n`)) changed++;
  if (fallbacks.has(entry.id)) continue;

  const ext = extension(entry.type);
  const raw = path.join(rawDir(entry.type), `${entry.id}.${ext}`);
  const workflow = path.join("workflows", WORKFLOW_FILES[entry.workflow as WorkflowKey]);
  const deps = [stamp, workflow];
  if (entry.reference) {
    const ref = manifest.assets.find((a) => a.id === entry.reference);
    if (ref) deps.push(path.join(rawDir(ref.type), `${ref.id}.${extension(ref.type)}`));
  }
  rules.push(`${raw}: ${deps.join(" ")}\n\t$(NODE) scripts/comfy.ts gen --id ${entry.id}\n`);
  const group = entry.type === "music" ? "music" : entry.type === "sfx" ? "sfx" : entry.type === "frame" ? "frames" : entry.workflow === "krea2" ? "styled" : "base";
  groups[group]!.push(raw);

  if (entry.type === "image" || entry.type === "frame") {
    const processed = path.join(assetDir(entry.type), `${entry.id}.png`);
    if (entry.transparent && entry.key !== "all") {
      const cut = sourceOf(entry);
      rules.push(`${cut}: ${raw} workflows/${WORKFLOW_FILES.birefnet}\n\t$(NODE) scripts/comfy.ts cut --id ${entry.id}\n`);
      groups["cutouts"]!.push(cut);
    }
    // Frames of one animation share a crop box, so each depends on every member's source.
    const sources = animationOf(manifest, entry).filter((a) => !fallbacks.has(a.id)).map(sourceOf);
    rules.push(`${processed}: ${sources.join(" ")} ${stamp} scripts/process.ts ${PROMPTS_FILE}\n\t$(NODE) scripts/process.ts --id ${entry.id}\n`);
    groups["processed"]!.push(processed);
  } else {
    const processed = path.join(assetDir(entry.type), `${entry.id}.${ext}`);
    rules.push(`${processed}: ${raw} ${stamp} scripts/process.ts scripts/lib/audio-tools.ts\n\t$(NODE) scripts/process.ts --id ${entry.id}\n`);
    groups["processed"]!.push(processed);
  }
}

// Entries that have left the manifest.
if (existsSync(ENTRIES)) for (const f of readdirSync(ENTRIES)) if (!wanted.has(f)) rmSync(path.join(ENTRIES, f));

const lines = ["# Generated by scripts/gen-rules.ts from assets/manifest.json. Do not edit.", ""];
for (const [name, files] of Object.entries(groups)) lines.push(`ASSETS_${name.toUpperCase()} := ${files.join(" ")}`, "");
lines.push(...rules);
const wrote = writeIfChanged(OUT, lines.join("\n"));
// Unchanged content keeps its file, but the fragment must look newer than the manifest or make would run this every time.
if (!wrote) utimesSync(OUT, new Date(), new Date());
const total = Object.values(groups).reduce((n, g) => n + g.length, 0);
console.log(`gen-rules: ${manifest.assets.length} manifest entries, ${total} targets, ${fallbacks.size} fallback(s) left out; ${changed} entry file(s) changed; ${OUT} ${wrote ? "rewritten" : "unchanged"}`);
